"""Step 23: does chain-of-thought generation add anything on top of query
decomposition (Step 19), for the same 3 multi-hop questions -- including the
one with the known Article 54(6)/53(2) citation regression under
recursive+headers (Step 18)?

Four variants per question, on the current production corpus
(ai_act_corpus_recursive_ctxheaders):
  - baseline:            retrieve(question),                 PlainGenerator
  - cot:                 retrieve(question),                 CotGenerator
  - decomposed:          retrieve(sub_q) per sub-question,    PlainGenerator
  - decomposed_cot:      retrieve(sub_q) per sub-question,    CotGenerator

Sub-questions still come from eval/decomposed_questions.jsonl (externally
generated by Sonnet-5 -- see DECOMPOSITION_INSTRUCTIONS.md). Chain-of-thought
is pure prompt engineering on top of the same Groq generation call, so it
doesn't need a separate external-judging round trip the way decomposition's
sub-question generation did (Rule 1: Groq is fine for generation).

Precision/Recall come from eval/span_scoring.py, same as Step 19/20.

Run with: python -m eval.decomposition_cot_experiment
"""

import json
from pathlib import Path

from app.core import config
from app.core.models import RetrievedContext
from app.pipelines.plain.generation import PlainGenerator
from app.pipelines.plain.retrieval import PlainRetriever
from eval.cot_generation import CotGenerator
from eval.experiment_lib import use_local_qdrant
from eval.span_scoring import ChunkSpanLookup, load_qrels_spans, precision_recall

EVAL_DIR = Path(__file__).parent
GOLDEN_SET_PATH = EVAL_DIR / "golden_set.jsonl"
DECOMPOSED_PATH = EVAL_DIR / "decomposed_questions.jsonl"

# Current production config (Step 22) -- see .env / DEPLOYMENT.md.
CORPUS_BASE_NAME = "ai_act_corpus_recursive_ctxheaders"

# Qdrant Cloud connectivity was down from this machine for a while (see
# PROGRESS.md's Step 22/23/24 network notes) and has come back, at least
# intermittently -- confirmed by running this script against production
# directly (see PROGRESS.md's Step 25 entry). Defaults back to the local,
# on-disk copy for routine re-runs, since Cloud connectivity isn't reliably
# stable yet; set False to target production again when needed.
USE_LOCAL_QDRANT = True


def _load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _merge_dedupe(context_lists: list[list[RetrievedContext]]) -> list[RetrievedContext]:
    seen_ids = set()
    merged = []
    for contexts in context_lists:
        for c in contexts:
            if c.chunk.id not in seen_ids:
                merged.append(c)
                seen_ids.add(c.chunk.id)
    return merged


def main() -> None:
    if not DECOMPOSED_PATH.exists():
        raise SystemExit(
            f"{DECOMPOSED_PATH} not found -- run eval/export_questions_for_decomposition.py, "
            f"get it decomposed externally per DECOMPOSITION_INSTRUCTIONS.md, and save the "
            f"result there first."
        )

    golden_set = {item["question"]: item for item in _load_jsonl(GOLDEN_SET_PATH)}
    decomposed = {item["question"]: item["sub_questions"] for item in _load_jsonl(DECOMPOSED_PATH)}
    qrels = load_qrels_spans()
    lookup = ChunkSpanLookup()

    plain_generator = PlainGenerator()
    cot_generator = CotGenerator()

    if USE_LOCAL_QDRANT:
        use_local_qdrant()
    config.QDRANT_COLLECTION = CORPUS_BASE_NAME
    config.CHUNKING_STRATEGY = "recursive"
    retriever = PlainRetriever()
    collection = config.collection_name()
    print(f"\n{'=' * 110}\nCorpus: {CORPUS_BASE_NAME}  ({collection})\n{'=' * 110}")

    for question, sub_questions in decomposed.items():
        golden = golden_set[question]
        relevant_spans = qrels.get(question, [])

        print(f"\n--- {question[:90]}")
        print(f"    expected_source_doc: {golden['expected_source_doc']}")
        print(f"    sub-questions: {sub_questions}")

        baseline_contexts = _merge_dedupe([retriever.retrieve(question)])
        decomposed_contexts = _merge_dedupe([retriever.retrieve(sq) for sq in sub_questions])

        variants = [
            ("baseline", baseline_contexts, plain_generator),
            ("cot", baseline_contexts, cot_generator),
            ("decomposed", decomposed_contexts, plain_generator),
            ("decomposed_cot", decomposed_contexts, cot_generator),
        ]

        for label, contexts, generator in variants:
            retrieved_docs = {c.chunk.source_doc for c in contexts}
            hit = golden["expected_source_doc"] in retrieved_docs
            pr = precision_recall(contexts, relevant_spans, lookup)
            answer = generator.generate(question, contexts)

            pr_str = f"P={pr[0]:.2f} R={pr[1]:.2f}" if pr else "n/a"
            print(f"    [{label:15s}] {len(contexts)} chunks, hit={hit}, {pr_str}")
            print(f"      sources: {', '.join(answer.citations)}")
            print(f"      answer: {answer.text[:280]}")


if __name__ == "__main__":
    main()
